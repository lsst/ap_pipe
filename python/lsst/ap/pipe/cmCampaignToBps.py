"""Build a standalone BPS submission file from a single-step CM Service
campaign definition.

The generated BPS yaml is not intended to be used directly, but is a
representation of the submission used by Campaign Management. This script is
called when building ``ap_pipe`` and generates
``bps/LSSTCam/bps_Daytime.yaml``.

Examples
--------
Rebuild the Daytime AP submission from the package root:

.. code-block:: bash

   python -m lsst.ap.pipe.cmCampaignToBps \\
       scripts/LSSTCam/ap_daytime_cm_campaign.yaml \\
       bps/LSSTCam/bps_Daytime.yaml

``scons bps/LSSTCam/bps_Daytime.yaml`` runs the same command.
"""

__all__ = ["makeBpsConfig", "readCampaign", "writeBpsConfig", "main"]

import argparse
import re

import yaml

# CM template expressions, without whitespace, that evaluate to the
# campaign's day_obs.
_DAY_OBS_EXPRESSIONS = frozenset({"yesterday|as_day_obs", "day_obs"})
_TEMPLATE_PATTERN = re.compile(r"\$\{\{(.*?)\}\}")

# CM Service defaults for manifest fields the campaign may omit; see the
# WmsSpec and FacilitySpec models in lsst-dm/cm-service.
_WMS_DEFAULTS = {
    "service_class": "lsst.ctrl.bps.htcondor.HTCondorService",
    "auto_provision": False,
    "provisioned_node_count": 10,
    "provisioned_cpu_count": 16,
    "provisioned_max_wall_time": "0-1:00:00",
    "provisioned_idle_time": 900,
    "provisioned_check_interval": 600,
    "provisioned_extra_arguments": [],
    "auto_release": True,
    "auto_release_expr": "HoldReasonCode >= 6",
}
_SITE_DEFAULTS = {
    "facility": "SLAC",
    "provisioned_platform": "s3df",
    "provisioned_queue": "milano",
    "provisioned_account_group": "rubin:developers",
}
_AGGREGATE_DEFAULT = ["--output {submitPath}/{uniqProcName}_prov.qg"]

# BPS manifest list fields and the BPS keys that take them joined by spaces.
_EXTRA_OPTIONS = {
    "extra_init_options": "extraInitOptions",
    "extra_qgraph_options": "extraQgraphOptions",
    "extra_run_quantum_options": "extraRunQuantumOptions",
    "extra_update_qgraph_options": "extraUpdateQgraphOptions",
}

_HEADER = """\
# Generated by `scons` from {source}; edit that file instead.
#
# Example BPS submission of the CM Service campaign. Set the day_obs to
# process in a wrapper file and submit that:
#
#   includeConfigs:
#     - ${{AP_PIPE_DIR}}/{target}
#   dayObs: 20261112
#
"""


def _replaceTemplate(match):
    if "".join(match.group(1).split()) not in _DAY_OBS_EXPRESSIONS:
        raise ValueError(f"Unsupported CM template expression: {match.group(0)}")
    return "{dayObs}"


def _renderTemplates(value):
    """Replace the CM day_obs template expressions in all strings of a
    YAML object with the BPS variable ``{dayObs}``.
    """
    if isinstance(value, str):
        return _TEMPLATE_PATTERN.sub(_replaceTemplate, value)
    if isinstance(value, list):
        return [_renderTemplates(item) for item in value]
    if isinstance(value, dict):
        return {key: _renderTemplates(item) for key, item in value.items()}
    return value


def _selectManifest(documents, kind):
    """Return the single manifest of a kind, or the one marked default."""
    candidates = [doc for doc in documents if doc.get("kind") == kind]
    if len(candidates) > 1:
        candidates = [doc for doc in candidates if doc.get("metadata", {}).get("default")]
    if len(candidates) != 1:
        raise ValueError(f"Campaign needs exactly one {kind!r} manifest, or one marked default.")
    return _renderTemplates(candidates[0])


def _selectStep(documents):
    steps = [
        doc for doc in documents
        if doc.get("kind") == "node" and doc.get("metadata", {}).get("kind") == "step"
    ]
    if len(steps) != 1:
        raise ValueError(f"Campaign needs exactly one step node for one BPS file; found {len(steps)}.")
    return _renderTemplates(steps[0])


def _asList(value):
    if value is None:
        return []
    if isinstance(value, str):
        return [value]
    return list(value)


def readCampaign(path):
    """Read the manifests of a CM Service campaign definition.

    Parameters
    ----------
    path : `str`
        Multi-document campaign YAML file.

    Returns
    -------
    documents : `list` [`dict`]
        The non-empty YAML documents, in file order.
    """
    with open(path) as stream:
        return [doc for doc in yaml.safe_load_all(stream) if doc]


def makeBpsConfig(documents):
    """Build a BPS submission config from CM Service campaign manifests.

    Parameters
    ----------
    documents : `list` [`dict`]
        Campaign manifests, as returned by `readCampaign`. The campaign must
        have one step node, and one ``bps``, ``butler``, ``lsst``, ``wms``
        and ``site`` manifest each (or one of each kind marked default).

    Returns
    -------
    config : `dict`
        BPS configuration, in the key order CM Service writes it.

    Raises
    ------
    ValueError
        Raised if the campaign does not have the manifests listed above, or
        uses a CM template expression other than the campaign's day_obs.
    """
    campaign = _selectManifest(documents, "campaign")
    step = _selectStep(documents)
    lsst = _selectManifest(documents, "lsst")["spec"]
    butler = _selectManifest(documents, "butler")["spec"]
    wms = _WMS_DEFAULTS | _selectManifest(documents, "wms")["spec"]
    site = _SITE_DEFAULTS | _selectManifest(documents, "site")["spec"]
    # Step-level BPS settings take precedence over the campaign manifest.
    bps = _selectManifest(documents, "bps")["spec"] | (step["spec"].get("bps") or {})

    config = {}
    for key in ("project", "campaign"):
        if lsst.get(key):
            config[key] = lsst[key]
    if bps.get("variables"):
        config.update({key: str(value) for key, value in bps["variables"].items()})

    config["pipelineYaml"] = bps["pipeline_yaml"]
    includes = []
    for manifest in (lsst, bps, butler, wms, site):
        for include in _asList(manifest.get("include_files")):
            if include not in includes:
                includes.append(include)
    if includes:
        config["includeConfigs"] = includes

    # CM exports the lsst manifest environment in the shell that runs
    # `bps submit`; a standalone submission needs it in the jobs.
    environment = (lsst.get("environment") or {}) | (bps.get("environment") or {})
    if environment:
        config["environment"] = {key: str(value) for key, value in environment.items()}

    collections = butler["collections"]
    config["payload"] = {
        "payloadName": campaign["metadata"]["name"],
        "butlerConfig": butler["repo"],
        "inCollection": ",".join(_asList(collections["campaign_input"])),
        "output": collections["campaign_public_output"],
        "dataQuery": " AND ".join(butler["predicates"]),
    }
    for field, key in _EXTRA_OPTIONS.items():
        if bps.get(field):
            config[key] = " ".join(bps[field])
    if bps.get("clustering"):
        config["cluster"] = bps["clustering"]

    config["extraAggregateOptions"] = " ".join(bps.get("extra_aggregate_options") or _AGGREGATE_DEFAULT)
    config.update(bps.get("literals") or {})

    config["wmsServiceClass"] = wms["service_class"]
    config["computeSite"] = site["facility"]
    config.update(site.get("literals") or {})
    if wms["auto_release"]:
        config["releaseExpr"] = wms["auto_release_expr"]
    if wms.get("batch_name"):
        config["nodeset"] = wms["batch_name"]
    if wms["auto_provision"]:
        extraOptions = [f"--cpu {wms['provisioned_cpu_count']}", *wms["provisioned_extra_arguments"]]
        config["provisionResources"] = True
        config["provisioning"] = {
            "provisioningNodeCount": wms["provisioned_node_count"],
            "provisioningMaxIdleTime": wms["provisioned_idle_time"],
            "provisioningMaxWallTime": wms["provisioned_max_wall_time"],
            "provisioningCheckInterval": wms["provisioned_check_interval"],
            "provisioningQueue": site["provisioned_queue"],
            "provisioningAccountingUser": site["provisioned_account_group"],
            "provisioningPlatform": site["provisioned_platform"],
            "provisioningExtraOptions": " ".join(extraOptions),
        }
    return config


def writeBpsConfig(config, path, source):
    """Write a BPS config made by `makeBpsConfig` with a usage header.

    Parameters
    ----------
    config : `dict`
        BPS configuration.
    path : `str`
        Output file, relative to the package root to give a usable header.
    source : `str`
        Campaign file the config was made from, named in the header.
    """
    with open(path, "w") as stream:
        stream.write(_HEADER.format(source=source, target=path))
        yaml.safe_dump(config, stream, sort_keys=False, width=4096)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Build a standalone BPS submission file from a single-step CM Service campaign."
    )
    parser.add_argument("campaign", help="CM Service campaign definition YAML.")
    parser.add_argument("output", help="BPS submission YAML to write.")
    args = parser.parse_args(argv)

    writeBpsConfig(makeBpsConfig(readCampaign(args.campaign)), args.output, args.campaign)


if __name__ == "__main__":
    main()
